/// A key's text in a language (`ru_ru` or English), none if Emotecraft has no such key.
pub fn get(lang: &str, key: &str) -> Option<&'static str> {
    let find = |t: &'static [(&str, &str)]| t.iter().find(|(k, _)| *k == key).map(|(_, v)| *v);
    if lang.eq_ignore_ascii_case("ru_ru") {
        if let Some(v) = find(RU_RU) {
            return Some(v);
        }
    }
    find(EN_US)
}
