// Makes the port's generated sources from the original's files in tools/assets/:
// `node tools/generate.mjs`.
//   mixins/particlerain/lang.rs      the texts: the original's en_us.json and ru_ru.json,
//                                    tools/assets/ru_port.json for the lines its Russian lacks,
//                                    and en_port.json + ru_port.json for the port's additions
//   mixins/particlerain/defaults.rs  the original's assets/particlerain/particles.json
//   mixins/particlerain/textures.rs  the original's particle textures (PNG bytes)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "tools", "assets");
const out = join(root, "mixins", "particlerain");
const read = (name) => JSON.parse(readFileSync(join(assets, name), "utf8"));

// ---- lang.rs ----
const en = read("en_us.json");
// The port's own lines (its additions), after the original's.
for (const [k, v] of Object.entries(read("en_port.json"))) {
  if (k in en) throw new Error(`en_port.json: ${k} is in the original's en_us.json`);
  en[k] = v;
}
const ruOriginal = read("ru_ru.json");
const ruPort = read("ru_port.json");
const ru = {};
// Lines of the original's Russian file for keys its English file still has (older keys are unused).
for (const [k, v] of Object.entries(ruOriginal)) if (k in en) ru[k] = v;
for (const [k, v] of Object.entries(ruPort)) {
  if (!(k in en)) throw new Error(`ru_port.json: ${k} is not in en_us.json`);
  if (k in ru) throw new Error(`ru_port.json: ${k} is in the original's ru_ru.json`);
  ru[k] = v;
}
const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const table = (name, map) =>
  `pub(super) const ${name}: &[(&str, &str)] = &[\n` +
  Object.entries(map).map(([k, v]) => `    (${lit(k)}, ${lit(v)}),\n`).join("") +
  `];\n`;
writeFileSync(
  join(out, "lang.rs"),
  `// Particle Rain's texts (generated by tools/generate.mjs): the original's \`en_us.json\` and
// \`ru_ru.json\`, and the port's Russian for the lines the original's Russian file lacks
// (tools/assets/ru_port.json). \`t\` is \`Component.translatable\` resolved: Russian when the game
// is in Russian, else English; a key with no text is shown as itself, as in Java.
//
// Particle Rain by PigCart (https://github.com/PigCart/particle-rain), MIT.

pub(super) fn russian() -> bool {
    horizon_client::lang::code().starts_with("ru")
}

${table("ENGLISH", en)}
${table("RUSSIAN", ru)}
fn find(table: &[(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// The text for \`key\` in the game's language, if the mod has one.
pub(super) fn get(key: &str) -> Option<&'static str> {
    if russian() { find(RUSSIAN, key).or_else(|| find(ENGLISH, key)) } else { find(ENGLISH, key) }
}

/// \`Component.translatable(key)\`: the text, else the key.
pub(super) fn t(key: &str) -> String {
    get(key).map_or_else(|| key.to_owned(), str::to_owned)
}

/// \`Component.translatable(key, args)\`: \`%s\` in order, \`%1$s\` by place, \`%%\`.
pub(super) fn tf(key: &str, args: &[&str]) -> String {
    let pattern = t(key);
    let mut out = String::new();
    let mut next = 0;
    let mut chars = pattern.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            out.push(c);
            continue;
        }
        let mut spec = String::new();
        while let Some(&d) = chars.peek() {
            spec.push(d);
            chars.next();
            if d.is_ascii_alphabetic() || d == '%' {
                break;
            }
        }
        if spec == "%" {
            out.push('%');
            continue;
        }
        let index = spec.split_once('$').and_then(|(n, _)| n.parse::<usize>().ok()).map(|n| n - 1).unwrap_or_else(|| {
            next += 1;
            next - 1
        });
        out.push_str(args.get(index).copied().unwrap_or(""));
    }
    out
}
`,
);

// ---- defaults.rs ----
const particles = readFileSync(join(assets, "particles.json"), "utf8");
if (particles.includes('"##')) throw new Error("particles.json can't go in a raw string");
writeFileSync(
  join(out, "defaults.rs"),
  `// The original's built-in particles (\`assets/particlerain/particles.json\`, generated into this
// file by tools/generate.mjs): what a resource pack's own file is merged over, and what each
// particle's Reset goes back to.
//
// Particle Rain by PigCart (https://github.com/PigCart/particle-rain), MIT.

pub(super) const PARTICLES_JSON: &str = r##"${particles}"##;
`,
);

// ---- textures.rs ----
const bytes = (buf) => {
  let s = "";
  let line = 0;
  for (const b of buf) {
    let c;
    if (b > 0x20 && b < 0x7f && b !== 0x22 && b !== 0x5c) c = String.fromCharCode(b);
    else c = "\\x" + b.toString(16).padStart(2, "0");
    s += c;
    line += c.length;
    if (line > 96) {
      s += "\\\n";
      line = 0;
    }
  }
  return s;
};
const textures = readdirSync(join(assets, "textures")).filter((f) => f.endsWith(".png")).sort();
writeFileSync(
  join(out, "textures.rs"),
  `// The original's particle textures (\`assets/particlerain/textures/particle/*.png\`, generated into
// this file by tools/generate.mjs), packed into the game's atlas as \`particlerain:particle/<name>\`
// (atlas.rs).
//
// Particle Rain by PigCart (https://github.com/PigCart/particle-rain), MIT.

/// Each texture's name and PNG file.
pub const TEXTURES: &[(&str, &[u8])] = &[
${textures.map((f) => `    ("${f.replace(/\.png$/, "")}", b"${bytes(readFileSync(join(assets, "textures", f)))}"),`).join("\n")}
];
`,
);
console.log(`lang.rs: ${Object.keys(en).length} English, ${Object.keys(ru).length} Russian; textures.rs: ${textures.length}`);
