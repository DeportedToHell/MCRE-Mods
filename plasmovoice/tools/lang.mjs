// Makes mixins/plasmovoice/lang.rs from Plasmo Voice's texts:
//   node tools/lang.mjs <plasmo-voice checkout> <plasmo-voice-crowdin, branch pv> [out.rs]
// English: client/src/main/resources/assets/plasmovoice/lang/en_us.json; Russian: Crowdin's
// ru_RU/client.json (it lacks some keys: the game falls back to English for those).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [plasmo, crowdin, out = new URL("../mixins/plasmovoice/lang.rs", import.meta.url)] = process.argv.slice(2);
const en = JSON.parse(readFileSync(join(plasmo, "client/src/main/resources/assets/plasmovoice/lang/en_us.json"), "utf8"));
const ru = JSON.parse(readFileSync(join(crowdin, "ru_RU/client.json"), "utf8"));
// Horizon's own texts, for what the port adds (not in Plasmo Voice).
Object.assign(en, {
  "gui.plasmovoice.overlay.tab_list_icons": "Tab List Icons",
  "gui.plasmovoice.overlay.tab_list_icons.tooltip": "Horizon addition: a microphone before the names of players with Plasmo Voice in the player list (Tab): white while they talk, crossed out otherwise.",
});
Object.assign(ru, {
  "gui.plasmovoice.overlay.tab_list_icons": "Иконки в Tab",
  "gui.plasmovoice.overlay.tab_list_icons.tooltip": "Дополнение Horizon: микрофон перед никами игроков с Plasmo Voice в списке игроков (Tab): белый, когда игрок говорит, перечёркнутый в остальное время.",
});

const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const table = (name, map) =>
  `fn ${name}(key: &str) -> Option<&'static str> {\n    Some(match key {\n` +
  Object.entries(map)
    .map(([k, v]) => `        ${lit(k)} => ${lit(v)},\n`)
    .join("") +
  `        _ => return None,\n    })\n}\n`;

const rs = `// Plasmo Voice's texts: its \`en_us.json\` and Crowdin's \`ru_RU/client.json\` (generated by
// tools/lang.mjs). \`t\` is \`Component.translatable\`: Russian when the game is in Russian, English
// for a key Russian lacks (the game loads en_us under every language), then what the server sent
// (\`LanguagePacket\`: activation and source line names), then the key itself.
//
// This Source Code Form is a port of Plasmo Voice (https://github.com/plasmoapp/plasmo-voice), LGPL-3.0.

pub(super) fn russian() -> bool {
    horizon_client::lang::code().starts_with("ru")
}

/// The game's language code as Plasmo Voice asks the server for it (\`ru_ru\`).
pub(super) fn code() -> String {
    horizon_client::lang::code().to_lowercase()
}

${table("english", en)}
${table("russian_text", ru)}
/// The text for \`key\`.
pub(super) fn t(key: &str) -> String {
    let local = if russian() { russian_text(key).or_else(|| english(key)) } else { english(key) };
    if let Some(s) = local {
        return s.to_owned();
    }
    if let Some(s) = super::plasmovoice_glue::server_text(key) {
        return s;
    }
    if horizon_client::lang::has(key) {
        return horizon_client::lang::get(key);
    }
    key.to_owned()
}

/// \`String.format\` of \`key\`'s text: \`%s\` in order, \`%1$s\`, \`%2$s\` by place, \`%d\` as \`%s\`.
pub(super) fn tf(key: &str, args: &[&str]) -> String {
    format(&t(key), args)
}

pub(super) fn format(pattern: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut next = 0;
    let mut chars = pattern.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            out.push(c);
            continue;
        }
        let mut spec = String::new();
        while let Some(&d) = chars.peek() {
            spec.push(d);
            chars.next();
            if d.is_ascii_alphabetic() || d == '%' {
                break;
            }
        }
        if spec == "%" {
            out.push('%');
            continue;
        }
        let index = spec.split_once('$').and_then(|(n, _)| n.parse::<usize>().ok()).map(|n| n - 1).unwrap_or_else(|| {
            next += 1;
            next - 1
        });
        out.push_str(args.get(index).copied().unwrap_or(""));
    }
    out
}
`;
writeFileSync(out, rs);
console.log(`wrote ${out}: ${Object.keys(en).length} English, ${Object.keys(ru).length} Russian`);
