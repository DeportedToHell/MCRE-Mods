// Makes mixins/pingwheel/lang.rs from Ping Wheel's texts: `node tools/lang.mjs`.
// English: the original's assets/pingwheel/lang/en_us.json (branch 26.3, copied to tools/assets/).
// Russian: the port's own tools/assets/ru_ru.json (the original has none).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => JSON.parse(readFileSync(join(root, "tools", "assets", name), "utf8"));
const en = read("en_us.json");
const ru = read("ru_ru.json");
for (const k of Object.keys(ru)) if (!(k in en)) throw new Error(`ru_ru.json: ${k} is not in en_us.json`);

const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const table = (name, map) =>
  `pub(super) const ${name}: &[(&str, &str)] = &[\n` +
  Object.entries(map).map(([k, v]) => `    (${lit(k)}, ${lit(v)}),\n`).join("") +
  `];\n`;

const rs = `// Ping Wheel's texts (generated by tools/lang.mjs): the original's \`en_us.json\` and the port's
// Russian. \`t\` is \`Component.translatable\` resolved: Russian when the game is in Russian, else
// English. \`inject\` puts them into the game's language too (as a mod's lang file would be), so
// \`Text::translate\` of these keys works in chat, the subtitles and the server's answers.
//
// Ping Wheel by Luken (https://github.com/LukenSkyne/Minecraft-Ping-Wheel), MIT.

pub(super) fn russian() -> bool {
    horizon_client::lang::code().starts_with("ru")
}

${table("ENGLISH", en)}
${table("RUSSIAN", ru)}
fn find(table: &[(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// The text for \`key\` in the game's language, else the key.
pub(super) fn t(key: &str) -> String {
    let local = if russian() { find(RUSSIAN, key).or_else(|| find(ENGLISH, key)) } else { find(ENGLISH, key) };
    local.map_or_else(|| key.to_owned(), str::to_owned)
}

/// \`String.format\` of \`key\`'s text: \`%s\` in order, \`%1$s\` by place, \`%%\`.
pub(super) fn tf(key: &str, args: &[&str]) -> String {
    format(&t(key), args)
}

pub(super) fn format(pattern: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut next = 0;
    let mut chars = pattern.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            out.push(c);
            continue;
        }
        let mut spec = String::new();
        while let Some(&d) = chars.peek() {
            spec.push(d);
            chars.next();
            if d.is_ascii_alphabetic() || d == '%' {
                break;
            }
        }
        if spec == "%" {
            out.push('%');
            continue;
        }
        let index = spec.split_once('$').and_then(|(n, _)| n.parse::<usize>().ok()).map(|n| n - 1).unwrap_or_else(|| {
            next += 1;
            next - 1
        });
        out.push_str(args.get(index).copied().unwrap_or(""));
    }
    out
}

/// The texts in the game's language (a resource pack's own keep theirs): once a language is
/// loaded, and again after each reload.
pub(super) fn inject() {
    let local: &[(&'static str, &'static str)] = if russian() { RUSSIAN } else { &[] };
    horizon_client::lang::pingwheel_lang::ensure(ENGLISH, local);
}
`;
writeFileSync(join(root, "mixins", "pingwheel", "lang.rs"), rs);
console.log(`lang.rs: ${Object.keys(en).length} English, ${Object.keys(ru).length} Russian`);
